    #[test]
    fn accrue_simple_matches_domain_cases() {
        // domain.md §6: 12% a year on 60,000,000 for one 365-day year.
        assert_eq!(
            accrue_simple(60_000_000, 1_200, 31_536_000, 0).unwrap(),
            (7_200_000, 0)
        );
        // Zero elapsed seconds keep the carried remainder, even at the largest inputs.
        assert_eq!(
            accrue_simple(u64::MAX, u64::MAX, 0, DENOMINATOR - 1).unwrap(),
            (0, DENOMINATOR - 1)
        );

        // The TypeScript generator, exactly: a 64-bit LCG whose output is `state >> 16`.
        let mut state: u64 = 0x4d59_5df4_d0f3_3173;
        let mut next = || {
            state = state
                .wrapping_mul(6_364_136_223_846_793_005)
                .wrapping_add(1_442_695_040_888_963_407);
            state >> 16
        };
        for (sample, [first, second, whole]) in ACCRUAL_ORACLE.iter().enumerate() {
            let principal = next();
            let rate_bps = next() % 50_001;
            let first_elapsed = next() % 100_000_000;
            let second_elapsed = next() % 100_000_000;
            let carried = next() % DENOMINATOR;

            let a = accrue_simple(principal, rate_bps, first_elapsed, carried).unwrap();
            let b = accrue_simple(principal, rate_bps, second_elapsed, a.1).unwrap();
            let c = accrue_simple(principal, rate_bps, first_elapsed + second_elapsed, carried)
                .unwrap();
            assert_eq!(a, *first, "sample {sample}, first accrual");
            assert_eq!(b, *second, "sample {sample}, second accrual");
            assert_eq!(c, *whole, "sample {sample}, whole accrual");
            assert_eq!((a.0 + b.0, b.1), c, "sample {sample}, split equals whole");
        }
    }

    #[test]
    fn accrue_simple_refuses_overflow_and_bad_remainder() {
        refused(
            accrue_simple(1, 1, 1, DENOMINATOR),
            ThetisError::InvalidField,
        );
        // The largest valid remainder is accepted.
        assert_eq!(accrue_simple(1, 1, 1, DENOMINATOR - 1).unwrap(), (1, 0));
        // u64::MAX × 10,000 × u64::MAX exceeds u128.
        refused(
            accrue_simple(u64::MAX, 10_000, u64::MAX, 0),
            ThetisError::ArithmeticOverflow,
        );
        // The oracle's two cases: the interest exceeds u64, then the numerator exceeds u128.
        refused(
            accrue_simple(u64::MAX, u64::MAX, 1, 0),
            ThetisError::ArithmeticOverflow,
        );
        refused(
            accrue_simple(u64::MAX, u64::MAX, 2, 0),
            ThetisError::ArithmeticOverflow,
        );
    }

