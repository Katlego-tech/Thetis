    /// A canonical decimal string field, parsed to `u64`.
    fn number(object: &serde_json::Value, name: &str) -> u64 {
        let text = object[name]
            .as_str()
            .unwrap_or_else(|| panic!("{name} is a decimal string"));
        let value: u64 = text.parse().unwrap_or_else(|_| panic!("{name} is a u64"));
        assert_eq!(value.to_string(), text, "{name} is canonical");
        value
    }

