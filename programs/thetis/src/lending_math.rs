    #[test]
    fn release_preview_refuses_domain_refusal_cases() {
        // The base input is valid; each case changes only the named fields.
        preview(BASE).unwrap();
        for (name, input, expected) in [
            (
                "haircut 10001",
                Input {
                    haircut_bps: 10_001,
                    ..BASE
                },
                ThetisError::InvalidField,
            ),
            (
                "LTV 10001",
                Input {
                    max_ltv_bps: 10_001,
                    ..BASE
                },
                ThetisError::InvalidField,
            ),
            (
                "sold above locked",
                Input {
                    sold_locked_quantity: 5,
                    ..BASE
                },
                ThetisError::InsufficientLocked,
            ),
            (
                "principal u64::MAX plus interest 1",
                Input {
                    principal: u64::MAX,
                    booked_interest: 1,
                    ..BASE
                },
                ThetisError::ArithmeticOverflow,
            ),
            (
                "buyer u64::MAX plus top-up 1",
                Input {
                    buyer_amount: u64::MAX,
                    seller_top_up: 1,
                    ..BASE
                },
                ThetisError::ArithmeticOverflow,
            ),
            (
                "numerator above u128",
                Input {
                    locked_quantity: u64::MAX,
                    sold_locked_quantity: 0,
                    value_per_kg: u64::MAX,
                    haircut_bps: 0,
                    ..BASE
                },
                ThetisError::ArithmeticOverflow,
            ),
            (
                "eligible value above u64",
                Input {
                    locked_quantity: 1 << 40,
                    sold_locked_quantity: 0,
                    value_per_kg: 1 << 40,
                    haircut_bps: 0,
                    ..BASE
                },
                ThetisError::ArithmeticOverflow,
            ),
        ] {
            assert_eq!(preview(input).unwrap_err(), expected.into(), "{name}");
        }
    }

    #[test]
    fn release_preview_floors_twice() {
        // 1 kg at 1 per kg with a 1 bps haircut: 0.9999 floors to 0.
        assert_eq!(
            preview(Input {
                locked_quantity: 1,
                value_per_kg: 1,
                haircut_bps: 1,
                max_ltv_bps: 10_000,
                ..ZERO
            })
            .unwrap(),
            ReleasePreview {
                debt_before: 0,
                confirmed_payment: 0,
                applied: 0,
                debt_after: 0,
                quantity_after: 1,
                eligible_value_after: 0,
                limit_after: 0,
                seller_surplus: 0,
                allowed: true,
                required_additional_top_up: 0,
            }
        );
        // Eligible 3 at 50%: the limit 1.5 floors to 1.
        assert_eq!(
            preview(Input {
                locked_quantity: 3,
                value_per_kg: 1,
                haircut_bps: 0,
                max_ltv_bps: 5_000,
                ..ZERO
            })
            .unwrap(),
            ReleasePreview {
                debt_before: 0,
                confirmed_payment: 0,
                applied: 0,
                debt_after: 0,
                quantity_after: 3,
                eligible_value_after: 3,
                limit_after: 1,
                seller_surplus: 0,
                allowed: true,
                required_additional_top_up: 0,
            }
        );
        // The oracle's case: eligible 4.5 floors to 4, then the limit 2.76 floors to 2. One
        // combined floor would give 3, and the debt of 3 would be allowed.
        assert_eq!(
            preview(Input {
                max_ltv_bps: 6_900,
                ..BASE
            })
            .unwrap(),
            ReleasePreview {
                debt_before: 5,
                confirmed_payment: 2,
                applied: 2,
                debt_after: 3,
                quantity_after: 3,
                eligible_value_after: 4,
                limit_after: 2,
                seller_surplus: 0,
                allowed: false,
                required_additional_top_up: 1,
            }
        );
    }
