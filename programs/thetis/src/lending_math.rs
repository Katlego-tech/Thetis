//! The lending maths, mirrored from `accrueSimple` and `previewRelease` in `packages/domain`.

use anchor_lang::prelude::*;

use crate::{error::ThetisError, state::Loan};

/// 10,000 bps × 365 days × 86,400 s: one interest unit per this much of rate × time × principal.
const ACCRUAL_DENOMINATOR: u128 = 315_360_000_000;

const BPS_DENOMINATOR: u128 = 10_000;

/// Simple interest, mirroring `accrueSimple`: the whole units of interest earned and the
/// remainder (below one unit) to carry into the next accrual.
pub fn accrue_simple(
    principal: u64,
    rate_bps: u64,
    elapsed: u64,
    carried: u64,
) -> Result<(u64, u64)> {
    require!(
        u128::from(carried) < ACCRUAL_DENOMINATOR,
        ThetisError::InvalidField
    );
    let numerator = u128::from(principal)
        .checked_mul(u128::from(rate_bps))
        .and_then(|product| product.checked_mul(u128::from(elapsed)))
        .and_then(|product| product.checked_add(u128::from(carried)))
        .ok_or(ThetisError::ArithmeticOverflow)?;
    let interest = u64::try_from(numerator / ACCRUAL_DENOMINATOR)
        .map_err(|_| error!(ThetisError::ArithmeticOverflow))?;
    // The remainder is below the denominator, which fits u64.
    let remainder = u64::try_from(numerator % ACCRUAL_DENOMINATOR)
        .map_err(|_| error!(ThetisError::ArithmeticOverflow))?;
    Ok((interest, remainder))
}

/// A loan's accrual brought up to `accrued_at`, computed but not written.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Accrual {
    pub booked_interest: u64,
    pub accrual_remainder: u64,
    pub accrued_at: i64,
}

/// Accrues the loan's interest from its checkpoint to `now`. A clock before the checkpoint is
/// `ArithmeticOverflow`. The caller writes the result only once the instruction is authorised.
pub fn accrue(loan: &Loan, now: i64) -> Result<Accrual> {
    let elapsed = u64::try_from(i128::from(now) - i128::from(loan.accrued_at))
        .map_err(|_| error!(ThetisError::ArithmeticOverflow))?;
    let (interest, accrual_remainder) = accrue_simple(
        loan.principal,
        u64::from(loan.rate_bps),
        elapsed,
        loan.accrual_remainder,
    )?;
    let booked_interest = loan
        .booked_interest
        .checked_add(interest)
        .ok_or(ThetisError::ArithmeticOverflow)?;
    Ok(Accrual {
        booked_interest,
        accrual_remainder,
        accrued_at: now,
    })
}

/// What a payment-confirmed release (or an advance) would leave, mirroring `previewRelease`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ReleasePreview {
    pub debt_before: u64,
    pub confirmed_payment: u64,
    pub applied: u64,
    pub debt_after: u64,
    pub quantity_after: u64,
    pub eligible_value_after: u64,
    pub limit_after: u64,
    pub seller_surplus: u64,
    pub allowed: bool,
    pub required_additional_top_up: u64,
}

#[allow(
    clippy::too_many_arguments,
    reason = "the arguments are the oracle's ten inputs, in its order"
)]
pub fn release_preview(
    principal: u64,
    booked_interest: u64,
    booked_fees: u64,
    buyer_amount: u64,
    seller_top_up: u64,
    locked_quantity: u64,
    sold_locked_quantity: u64,
    value_per_kg: u64,
    haircut_bps: u64,
    max_ltv_bps: u64,
) -> Result<ReleasePreview> {
    require!(
        u128::from(haircut_bps) <= BPS_DENOMINATOR && u128::from(max_ltv_bps) <= BPS_DENOMINATOR,
        ThetisError::InvalidField
    );
    require!(
        sold_locked_quantity <= locked_quantity,
        ThetisError::InsufficientLocked
    );
    let debt_before = u64::try_from(
        u128::from(principal) + u128::from(booked_interest) + u128::from(booked_fees),
    )
    .map_err(|_| error!(ThetisError::ArithmeticOverflow))?;
    let confirmed_payment = u64::try_from(u128::from(buyer_amount) + u128::from(seller_top_up))
        .map_err(|_| error!(ThetisError::ArithmeticOverflow))?;
    let applied = debt_before.min(confirmed_payment);
    // `applied <= debt_before` and `applied <= confirmed_payment`.
    let debt_after = debt_before - applied;
    let quantity_after = locked_quantity - sold_locked_quantity;
    let numerator = u128::from(quantity_after)
        .checked_mul(u128::from(value_per_kg))
        .and_then(|product| product.checked_mul(BPS_DENOMINATOR - u128::from(haircut_bps)))
        .ok_or(ThetisError::ArithmeticOverflow)?;
    let eligible_value_after = u64::try_from(numerator / BPS_DENOMINATOR)
        .map_err(|_| error!(ThetisError::ArithmeticOverflow))?;
    // The eligible value fits u64 and the multiplier is at most 10,000, so the limit is no
    // larger than the eligible value.
    let limit_after =
        u64::try_from(u128::from(eligible_value_after) * u128::from(max_ltv_bps) / BPS_DENOMINATOR)
            .map_err(|_| error!(ThetisError::ArithmeticOverflow))?;
    let allowed = debt_after <= limit_after;
    Ok(ReleasePreview {
        debt_before,
        confirmed_payment,
        applied,
        debt_after,
        quantity_after,
        eligible_value_after,
        limit_after,
        seller_surplus: confirmed_payment - applied,
        allowed,
        required_additional_top_up: if allowed { 0 } else { debt_after - limit_after },
    })
}

